create or replace function public.transition_flag_status(
  p_flag_id uuid,
  p_expected_status public.flag_status,
  p_new_status public.flag_status,
  p_moderation_reason text default null,
  p_report_id uuid default null
)
returns setof public.flags
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_actor uuid := (select auth.uid());
  v_is_admin boolean := false;
  v_flag public.flags%rowtype;
  v_updated public.flags%rowtype;
  v_reversed_event_id bigint;
  v_reason text := nullif(btrim(p_moderation_reason), '');
  v_did_update boolean;
begin
  if v_actor is null
     or not exists (select 1 from public.users account where account.id = v_actor)
  then
    raise exception 'Account is no longer active.' using errcode = '42501';
  end if;

  select coalesce(account.is_admin, false)
    into v_is_admin
    from public.users account
    where account.id = v_actor;

  select * into v_flag
    from public.flags
    where id = p_flag_id
    for update;

  if not found then
    raise exception 'Flag not found.' using errcode = 'P0002';
  end if;

  if v_flag.status <> p_expected_status::text then
    raise exception 'This flag changed since you opened it. Refresh and try again.'
      using errcode = 'P0001';
  end if;

  if p_expected_status = p_new_status then
    raise exception 'The requested status is already current.' using errcode = 'P0001';
  end if;

  if p_report_id is not null
     and not exists (
       select 1 from public.feedback report
       where report.id = p_report_id
         and report.body like '[REPORT]%'
         and report.moderation_reviewed_at is null
     )
  then
    raise exception 'The moderation report is missing or already closed.' using errcode = 'P0002';
  end if;

  if p_new_status = 'rejected'::public.flag_status then
    if not v_is_admin then
      raise exception 'Only Flagstone admins can reject reports.' using errcode = '42501';
    end if;
    if p_expected_status not in (
      'open'::public.flag_status, 'verified'::public.flag_status, 'resolved'::public.flag_status
    ) then
      raise exception 'A rejected report cannot be rejected again.' using errcode = 'P0001';
    end if;
    if v_reason is null or v_reason not in (
      'duplicate', 'not_accessibility_barrier', 'inaccurate', 'abusive_or_spam', 'other'
    ) then
      raise exception 'A valid rejection reason is required.' using errcode = '22023';
    end if;
  elsif p_expected_status = 'rejected'::public.flag_status
        and p_new_status = 'open'::public.flag_status then
    if not v_is_admin then
      raise exception 'Only Flagstone admins can restore reports.' using errcode = '42501';
    end if;
    if v_reason is null or v_reason not in (
      'moderator_error', 'new_evidence', 'corrected_report', 'other'
    ) then
      raise exception 'A valid restoration reason is required.' using errcode = '22023';
    end if;
  else
    if v_reason is not null or p_report_id is not null then
      raise exception 'Moderation metadata is only valid for reject or restore.' using errcode = '22023';
    end if;
  end if;

  -- The transaction-local marker and SECURITY DEFINER owner check are both
  -- required by the compatibility trigger. Neither a direct client role nor an
  -- unrelated owner-executed function can impersonate this moderation call.
  perform pg_catalog.set_config(
    'flagstone.phase03b_transition_actor',
    v_actor::text,
    true
  );

  update public.flags
     set status = p_new_status::text,
         last_moderation_reason_code = case
           when p_new_status = 'rejected'::public.flag_status
             or p_expected_status = 'rejected'::public.flag_status
           then v_reason
           else null
         end
   where id = p_flag_id
     and status = p_expected_status::text
   returning * into v_updated;

  v_did_update := found;
  perform pg_catalog.set_config('flagstone.phase03b_transition_actor', '', true);

  if not v_did_update then
    raise exception 'This flag changed since you opened it. Refresh and try again.'
      using errcode = 'P0001';
  end if;

  if p_new_status = 'rejected'::public.flag_status then
    insert into public.flag_moderation_events (
      flag_id, actor_id, action, reason_code, from_status, to_status, report_id
    ) values (
      p_flag_id, v_actor, 'reject', v_reason,
      p_expected_status::text, p_new_status::text, p_report_id
    );
  elsif p_expected_status = 'rejected'::public.flag_status
        and p_new_status = 'open'::public.flag_status then
    -- Pre-Phase03B rejected rows have no moderation event to link. They are
    -- still recoverable, but the new restore row deliberately keeps
    -- reverses_event_id NULL rather than inventing a historical rejection.
    select event.id into v_reversed_event_id
      from public.flag_moderation_events event
      where event.flag_id = p_flag_id
        and event.action = 'reject'
        and not exists (
          select 1 from public.flag_moderation_events recovery
          where recovery.reverses_event_id = event.id
        )
      order by event.created_at desc, event.id desc
      limit 1;

    insert into public.flag_moderation_events (
      flag_id, actor_id, action, reason_code, from_status, to_status,
      report_id, reverses_event_id
    ) values (
      p_flag_id, v_actor, 'restore', v_reason,
      p_expected_status::text, p_new_status::text, p_report_id, v_reversed_event_id
    );
  end if;

  return next v_updated;
end
$fn$;

