create or replace function public.moderate_report(
  p_report_id uuid,
  p_resolution text,
  p_expected_flag_status public.flag_status default null,
  p_moderation_reason text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_actor uuid := (select auth.uid());
  v_report public.feedback%rowtype;
  v_header text;
  v_match text[];
  v_target_kind text;
  v_target_id uuid;
  v_parent_flag_id uuid;
  v_reason text := nullif(btrim(p_moderation_reason), '');
  v_target_exists boolean;
  v_flag_has_storage boolean;
begin
  if v_actor is null
     or not coalesce((select private.current_user_is_admin()), false)
  then
    raise exception 'Only Flagstone admins can moderate reports.' using errcode = '42501';
  end if;

  if p_resolution not in (
    'no_action', 'flag_rejected', 'flag_removed', 'comment_removed', 'target_unavailable'
  ) then
    raise exception 'Unknown moderation resolution.' using errcode = '22023';
  end if;

  select * into v_report
    from public.feedback
    where id = p_report_id
    for update;

  if not found then
    raise exception 'Moderation report not found.' using errcode = 'P0002';
  end if;
  if v_report.moderation_reviewed_at is not null then
    if v_report.moderation_resolution = p_resolution
       and v_report.moderation_reason_code is not distinct from v_reason
    then
      return jsonb_build_object(
        'report_id', p_report_id,
        'resolution', v_report.moderation_resolution,
        'already_closed', true
      );
    end if;
    raise exception 'This moderation report was already closed with a different decision.'
      using errcode = 'P0001';
  end if;

  if v_report.body not like '[REPORT]%' then
    raise exception 'The feedback row is not a moderation report.' using errcode = '22023';
  end if;

  -- Malformed/future report envelopes are intentionally visible in the admin
  -- queue. An admin may close one as no_action without pretending its target
  -- was parsed. Every target-mutating resolution still requires the exact
  -- anchored v1/v2 envelope below.
  if p_resolution = 'no_action' then
    if v_reason is not null or p_expected_flag_status is not null then
      raise exception 'No-action does not accept reject metadata.' using errcode = '22023';
    end if;

    update public.feedback
       set moderation_reviewed_at = now(),
           moderation_reviewed_by = v_actor,
           moderation_resolution = 'no_action',
           moderation_action_intent = null,
           moderation_reason_code = null
     where id = p_report_id;

    return jsonb_build_object(
      'report_id', p_report_id,
      'resolution', 'no_action',
      'target_kind', null,
      'target_id', null,
      'already_closed', false
    );
  end if;

  v_header := split_part(v_report.body, E'\n', 1);
  v_match := regexp_match(
    v_header,
    '^\[REPORT\] v(1|2) target=(flag|comment) id=([0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12})(?: flag=([0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}))?(?: cat=[^ ]+)?$'
  );
  if v_match is null or position(E'\n' in v_report.body) = 0 then
    raise exception 'Malformed moderation report envelope.' using errcode = '22023';
  end if;

  v_target_kind := v_match[2];
  v_target_id := v_match[3]::uuid;
  v_parent_flag_id := nullif(v_match[4], '')::uuid;

  if v_target_kind = 'flag' and v_parent_flag_id is not null then
    raise exception 'Malformed flag report envelope.' using errcode = '22023';
  end if;
  -- `flag=` is optional for supported v1/v2 comment envelopes. The target
  -- comment id is authoritative; older and minimal clients did not include a
  -- parent flag id, and those reports must remain actionable.
  if v_target_kind = 'comment'
     and v_parent_flag_id is not null
     and exists (select 1 from public.flag_comments where id = v_target_id)
     and not exists (
       select 1 from public.flag_comments
       where id = v_target_id and flag_id = v_parent_flag_id
     )
  then
    raise exception 'Comment report parent flag does not match target.' using errcode = '22023';
  end if;

  if p_resolution = 'flag_rejected' then
    if v_target_kind <> 'flag' or p_expected_flag_status is null then
      raise exception 'Reject requires a flag report and expected status.' using errcode = '22023';
    end if;
    perform * from public.transition_flag_status(
      v_target_id,
      p_expected_flag_status,
      'rejected'::public.flag_status,
      v_reason,
      p_report_id
    );
  elsif p_resolution = 'flag_removed' then
    if v_target_kind <> 'flag' then
      raise exception 'Flag removal requires a flag report.' using errcode = '22023';
    end if;
    if v_reason is not null or p_expected_flag_status is not null then
      raise exception 'Flag removal does not accept reject metadata.' using errcode = '22023';
    end if;

    select (
      flag.photo_url is not null
      or flag.photo_object_key is not null
      or exists (
        select 1 from public.flag_photos photo where photo.flag_id = flag.id
      )
    ) into v_flag_has_storage
      from public.flags flag
      where flag.id = v_target_id
      for update;

    if not found then
      raise exception 'The reported flag is no longer available.' using errcode = 'P0002';
    end if;
    if v_flag_has_storage then
      raise exception 'Flag removal requires the canonical storage-safe deletion route.'
        using errcode = '55000';
    end if;
    delete from public.flags where id = v_target_id;
  elsif p_resolution = 'comment_removed' then
    if v_target_kind <> 'comment' then
      raise exception 'Comment removal requires a comment report.' using errcode = '22023';
    end if;
    if v_reason is not null or p_expected_flag_status is not null then
      raise exception 'Comment removal does not accept reject metadata.' using errcode = '22023';
    end if;
    delete from public.flag_comments where id = v_target_id;
    if not found then
      raise exception 'The reported comment is no longer available.' using errcode = 'P0002';
    end if;
  elsif p_resolution = 'target_unavailable' then
    if v_target_kind = 'flag' then
      select exists(select 1 from public.flags where id = v_target_id) into v_target_exists;
    else
      select exists(select 1 from public.flag_comments where id = v_target_id) into v_target_exists;
    end if;
    if v_target_exists then
      raise exception 'The reported target is still available.' using errcode = 'P0001';
    end if;
    if v_reason is not null or p_expected_flag_status is not null then
      raise exception 'Target-unavailable does not accept reject metadata.' using errcode = '22023';
    end if;
  end if;

  update public.feedback
     set moderation_reviewed_at = now(),
         moderation_reviewed_by = v_actor,
         moderation_resolution = p_resolution,
         moderation_action_intent = case
           when p_resolution in ('flag_rejected', 'flag_removed', 'comment_removed')
             then p_resolution
           else null
         end,
         moderation_reason_code = case
           when p_resolution = 'flag_rejected' then v_reason
           else null
         end
   where id = p_report_id;

  return jsonb_build_object(
    'report_id', p_report_id,
    'resolution', p_resolution,
    'target_kind', v_target_kind,
    'target_id', v_target_id,
    'already_closed', false
  );
end
$fn$;

revoke all on function public.moderate_report(
  uuid, text, public.flag_status, text
) from public, anon, authenticated, service_role;
grant execute on function public.moderate_report(
  uuid, text, public.flag_status, text
) to authenticated;

commit;
